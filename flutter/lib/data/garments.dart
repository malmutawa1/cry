/// Weighted allowance pieces for a selection (add-ons excluded).
int selectionPieces(Map<String, int> sel) {
  var total = 0;
  for (final g in garmentGroups) {
    for (final it in g.items) {
      final q = sel[it.id] ?? 0;
      if (q > 0 && !it.addon) total += q * it.pieces;
    }
  }
  return total;
}

int selectionUnits(Map<String, int> sel) => sel.values.fold(0, (s, n) => s + n);
